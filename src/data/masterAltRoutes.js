export function normalizePortId(id) {
  if (!id) return id;
  if (['SGTUA', 'SGPSP', 'SGKEP'].includes(id)) return 'SGSIN';
  if (['INIXY', 'INMUN'].includes(id)) return 'INMUN';
  if (['NLAMS', 'NLVLI', 'NLRTM'].includes(id)) return 'NLRTM';
  return id;
}

export function getMasterHraRoute(startId, destId) {
  const s = normalizePortId(startId);
  const d = normalizePortId(destId);
  const direct = s + '-' + d;
  if (MASTER_HRA_ROUTES[direct]) return MASTER_HRA_ROUTES[direct];
  const rev = d + '-' + s;
  if (MASTER_HRA_ROUTES[rev]) {
    const orig = MASTER_HRA_ROUTES[rev];
    return { ...orig, coordinates: [...orig.coordinates].reverse() };
  }
  return null;
}

